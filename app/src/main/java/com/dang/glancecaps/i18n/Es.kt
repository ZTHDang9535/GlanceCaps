    private val stepsRegex = Regex("([\\d,.]+) steps")
    private val goalRegex = Regex("Goal ([\\d,.]+)")

    private fun spaced(number: String): String = number.replace(",", "\u00A0")

    fun translate(text: String): String {
        exact[text]?.let { return it }
        var out = text
        for ((regex, replacement) in rules) out = regex.replace(out, replacement)
        out = stepsRegex.replace(out) { spaced(it.groupValues[1]) + " pasos" }
        out = goalRegex.replace(out) { "Meta " + spaced(it.groupValues[1]) }
        return out
    }
