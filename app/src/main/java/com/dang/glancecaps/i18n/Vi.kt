        Regex("^Updated to (.+)\$") to "Đã cập nhật lên \$1",
        Regex("^(\\d+) apps off\$") to "Tắt \$1 ứng dụng",
        Regex("^GlanceCaps v(\\S+) is available\\. You have v(\\S+)\\.\$") to "GlanceCaps v\$1 đã có. Bạn đang dùng v\$2.",
        Regex("^GlanceCaps (v\\S+)\$") to "GlanceCaps \$1",
        Regex("\\(API key\\)") to "(khóa API)",
