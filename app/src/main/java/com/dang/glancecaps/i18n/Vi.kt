        Regex("^Flood in (.+)\$") to "Lũ lụt tại \$1",
        Regex("^Earthquake in (.+)\$") to "Động đất tại \$1",
        Regex("(\\d+)h (\\d+)m\\b") to "\$1 giờ \$2 phút",
        Regex("(\\d+) min\\b") to "\$1 phút",
        Regex("-- min") to "-- phút",
        Regex("(\\d+) hours?\\b") to "\$1 giờ",
        Regex("^(\\d+) s\$") to "\$1 giây",
        Regex("([\\d,.]+) steps") to "\$1 bước",
        Regex("Goal ([\\d,.]+)") to "Mục tiêu \$1",
        Regex("Feels (-?\\d+)°") to "Cảm giác \$1°",
        Regex("H (-?\\d+)°  L (-?\\d+)°") to "Cao \$1°  Thấp \$2°",
        Regex("^Today (.+)\$") to "Hôm nay \$1",
        Regex("^Tomorrow (.+)\$") to "Ngày mai \$1",
