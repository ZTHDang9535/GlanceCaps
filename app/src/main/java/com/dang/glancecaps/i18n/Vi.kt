    private val rules: List<Pair<Regex, String>> = weatherWords + listOf(
        Regex("Super Typhoon") to "Siêu bão",
        Regex("Typhoon") to "Bão",
        Regex("Tropical Cyclone") to "Bão nhiệt đới",
        Regex("Tropical Storm") to "Bão nhiệt đới",
        Regex("Tropical Depression") to "Áp thấp nhiệt đới",
